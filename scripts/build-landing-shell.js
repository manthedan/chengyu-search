#!/usr/bin/env node
'use strict';
// Writes the landing page that app.js renders for a first-time visitor into
// public/index.html, so the first paint is the finished page. app.js keeps that
// DOM when its first render produces the same markup, so nothing pops in.
//
//   node scripts/build-landing-shell.js          rewrite public/index.html
//   node scripts/build-landing-shell.js --check  exit 1 if it is out of date
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const PUBLIC_DIR = path.join(__dirname, '..', 'public');
const INDEX_PATH = path.join(PUBLIC_DIR, 'index.html');
const START = '<!-- landing-shell:start (generated by scripts/build-landing-shell.js) -->';
const END = '<!-- landing-shell:end -->';

function listAppScripts(indexHtml) {
    return [...indexHtml.matchAll(/<script src="([^"]+)"><\/script>/g)].map(match => match[1]);
}

// Evaluates the page's scripts for a first-time visitor (no storage, no
// network) and returns `expression` evaluated after them.
function evaluateApp(expression, indexHtml = fs.readFileSync(INDEX_PATH, 'utf8')) {
    const app = { innerHTML: '', addEventListener: () => {} };
    const noop = () => {};
    const document = {
        body: { dataset: {} },
        activeElement: null,
        getElementById: id => (id === 'app' ? app : null),
        querySelector: () => null,
        querySelectorAll: () => [],
        createElement: () => ({ innerHTML: '' }),
        addEventListener: noop
    };
    const window = {
        location: { origin: '' },
        matchMedia: () => ({ matches: false }),
        speechSynthesis: { getVoices: () => [], addEventListener: noop, removeEventListener: noop }
    };
    const localStorage = { getItem: () => null, setItem: noop };
    const sandbox = { console, document, window, localStorage, setTimeout, clearTimeout, AbortController, fetch: noop };
    sandbox.globalThis = sandbox;
    const source = listAppScripts(indexHtml)
        .map(src => fs.readFileSync(path.join(PUBLIC_DIR, src), 'utf8'))
        .join('\n;\n');
    return vm.runInNewContext(`${source}\n;${expression}`, sandbox, { filename: 'landing-shell' });
}

function renderLandingShell(indexHtml) {
    return `<div class="app" id="app">${evaluateApp('render(); document.getElementById("app").innerHTML', indexHtml)}</div>`;
}

function loadExampleQueries(indexHtml) {
    return JSON.parse(evaluateApp('JSON.stringify(EXAMPLE_QUERIES)', indexHtml));
}

function buildIndexHtml(indexHtml = fs.readFileSync(INDEX_PATH, 'utf8')) {
    const start = indexHtml.indexOf(START);
    const end = indexHtml.indexOf(END);
    if (start < 0 || end < start) throw new Error(`public/index.html must contain ${START} … ${END}`);
    return `${indexHtml.slice(0, start + START.length)}\n    ${renderLandingShell(indexHtml)}\n    ${indexHtml.slice(end)}`;
}

if (require.main === module) {
    const current = fs.readFileSync(INDEX_PATH, 'utf8');
    const next = buildIndexHtml(current);
    if (process.argv.includes('--check')) {
        if (next !== current) {
            console.error('public/index.html landing shell is stale. Run: npm run build:landing');
            process.exit(1);
        }
        console.log('public/index.html landing shell is up to date.');
    } else if (next !== current) {
        fs.writeFileSync(INDEX_PATH, next);
        console.log('Updated public/index.html landing shell.');
    } else {
        console.log('public/index.html landing shell already up to date.');
    }
}

module.exports = { evaluateApp, renderLandingShell, loadExampleQueries, buildIndexHtml, START, END };
